/**
 * Счётчики на страницах направлений (/ventilyaciya, /otoplenie, /vodonagrevateli).
 *
 * Зачем отдельным файлом, а не строкой в блоке. th-page.js вставляет блок через
 * innerHTML, а он не выполняет скрипты. Внешние (со ссылкой) загрузчик
 * переподвешивает руками, написанные прямо в блоке с x-dc — НЕТ. Проверено
 * 27.08.2026: страница собралась, а все 13 чисел остались пустыми.
 *
 * Про порядок. Загрузчик вешает такие скрипты ДО support.js (тот идёт последним,
 * он и собирает разметку из x-dc). Значит, на момент запуска нужных элементов
 * в DOM ещё нет — ждём их появления, а не читаем сразу.
 *
 * Про честность. Числа берутся из data/index.json при каждом открытии. Не пришли
 * данные — место остаётся пустым, а не показывает старое значение. Прежние
 * страницы направлений именно так и врали: цифры лежали в конфиге gen_dir_blocks.py
 * от 30.07.2026 и там же устарели, а витрина обещала «под заказ» по разделам,
 * которых в каталоге уже сотни.
 *
 * Разметка — одно правило на все направления:
 *   <span data-group="teplovye-pushki"></span>          — сколько в группе
 *   <span data-sub="radiatory|Секционные"></span>       — сколько в подкатегории
 * Слева от «|» — slug группы, справа — имя подкатегории как в index.json.
 * ⚠️ Число обязано совпадать с тем, что покажет каталог по ссылке этой же плитки:
 *    одна плитка — один фильтр. Иначе страница обещает то, чего не выполняет.
 *
 * ⚠️ Почему файл называется dir-counts, а не vt-counts. Правило разметки менялось:
 * сперва подкатегория адресовалась просто именем, потом — «slug|Имя». Замена
 * содержимого по тому же адресу не помогла: jsDelivr держит скрипт у посетителя
 * долго, и старый кэш встречал новый блок — числа подкатегорий выходили пустыми
 * (поймано 27.08.2026 на живой /ventilyaciya). Ломаешь договор разметки —
 * меняй ИМЯ файла: у нового адреса кэша нет.
 */
(function () {
  var ДАННЫЕ = "https://raw.githubusercontent.com/tehnoholod369-glitch/tehnoholod-katalog/main/novy-dizayn/data/index.json";
  // Запасной адрес тех же данных. raw отвечает не всегда быстро: 13.09.2026
  // при повторных прогонах НОГИ один раз из трёх все 13 чисел на живой
  // /vodonagrevateli к десятой секунде так и остались пустыми, хотя разметка
  // и скрипт были на месте. Числа группы меняются от сборки к сборке, поэтому
  // кэш jsDelivr здесь допустим — пустое место хуже, чем счётчик суточной
  // давности. Порядок не меняем: сначала raw, зеркало только если raw молчит.
  var ЗЕРКАЛО = "https://cdn.jsdelivr.net/gh/tehnoholod369-glitch/tehnoholod-katalog@main/novy-dizayn/data/index.json";
  var ЖДАТЬ_МС = 12000, ШАГ_МС = 200, ОТВЕТ_МС = 6000;

  function склон(n, один, два, много) {
    var a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return много;
    if (b > 1 && b < 5) return два;
    if (b === 1) return один;
    return много;
  }

  function число(n) { return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " "); }

  function заполнить(d) {
    var по = {};
    (d.groups || []).forEach(function (g) { по[g.slug] = g; });

    // сводка направления: <span id="vt-svodka" data-svodka="ventilyaciya">
    var св = document.getElementById("vt-svodka");
    if (св) {
      var g = по[св.getAttribute("data-svodka") || ""];
      if (g) {
        писать(св, " В каталоге " + число(g.count) + " "
          + склон(g.count, "позиция", "позиции", "позиций") + " от "
          + число(g.brands) + " "
          + склон(g.brands, "производителя", "производителей", "производителей") + ".");
      }
    }

    document.querySelectorAll("[data-group]").forEach(function (el) {
      var g = по[el.getAttribute("data-group")];
      if (g) писать(el, число(g.count));
    });

    document.querySelectorAll("[data-sub]").forEach(function (el) {
      var части = (el.getAttribute("data-sub") || "").split("|");
      if (части.length < 2) return;               // без группы считать нечего
      var g = по[части[0]];
      if (!g) return;
      var имя = части.slice(1).join("|");
      (g.subs || []).forEach(function (s) {
        if (s.name === имя) писать(el, число(s.n));
      });
    });
  }

  // Пишем только когда текст действительно другой: иначе каждое заполнение
  // само поднимает волну мутаций, а на них подписан повторный проход ниже.
  function писать(el, текст) {
    if (el.textContent !== текст) el.textContent = текст;
  }

  function когдаПоявятся(готово) {
    var ждём = 0;
    (function тик() {
      if (document.querySelector("[data-sub],[data-group],#vt-svodka")) { готово(); return; }
      ждём += ШАГ_МС;
      if (ждём < ЖДАТЬ_МС) setTimeout(тик, ШАГ_МС);
      // не дождались — молчим: пустое место честнее выдуманного числа
    })();
  }

  /**
   * Почему одного заполнения мало. НОГИ 12.09.2026 поймали пустые «позиций»
   * на /vodonagrevateli и /otoplenie; причина найдена 13.09.2026 замером
   * на живой странице: 13 мест из 13 пустые в БРАУЗЕРЕ, при этом
   * data/index.json отдаёт 200 и нужные числа в нём есть, а сам скрипт
   * с jsDelivr приходит целым.
   *
   * Дело в порядке. На страницах направлений блок лежит в Tilda ЦЕЛИКОМ,
   * а не приезжает через th-page.js. Значит места под числа уже в DOM к моменту
   * запуска — ожидание срабатывает сразу, числа проставляются. И только ПОСЛЕ
   * этого support.js собирает разметку из <x-dc> и заменяет узлы новыми:
   * свежие копии приходят из шаблона пустыми, а второго прохода не было.
   *
   * Лечение — не «ждать подольше»: гонку это не убирает, ожидание и так
   * заканчивается успехом. Держим данные и повторяем заполнение, пока страница
   * перестраивается. Наблюдаем за DOM, добиваем только когда есть пустые места,
   * и через ДЕРЖАТЬ_МС отпускаем — наблюдатель не должен жить всю сессию.
   */
  var ДЕРЖАТЬ_МС = 20000, наблюдатель = null, отложено = null;

  function пустых() {
    var n = 0;
    Array.prototype.forEach.call(
      document.querySelectorAll("[data-sub],[data-group],#vt-svodka"),
      function (el) { if (!(el.textContent || "").trim()) n++; });
    return n;
  }

  function держать(d) {
    заполнить(d);
    if (!window.MutationObserver || !document.body) return;
    наблюдатель = new MutationObserver(function () {
      if (отложено) return;
      отложено = setTimeout(function () {
        отложено = null;
        if (пустых()) заполнить(d);
      }, 60);
    });
    наблюдатель.observe(document.body, { childList: true, subtree: true });
    setTimeout(function () {
      if (наблюдатель) { наблюдатель.disconnect(); наблюдатель = null; }
      if (отложено) { clearTimeout(отложено); отложено = null; }
    }, ДЕРЖАТЬ_МС);
  }

  function взять(адрес, мс) {
    return new Promise(function (готово, беда) {
      var упал = false;
      var таймер = setTimeout(function () { упал = true; беда(new Error("долго")); }, мс);
      fetch(адрес, { cache: "no-cache" })
        .then(function (r) { return r.ok ? r.json() : Promise.reject(new Error(r.status)); })
        .then(function (d) { if (!упал) { clearTimeout(таймер); готово(d); } })
        .catch(function (e) { if (!упал) { clearTimeout(таймер); беда(e); } });
    });
  }

  взять(ДАННЫЕ, ОТВЕТ_МС)
    .catch(function () { return взять(ЗЕРКАЛО, ОТВЕТ_МС); })
    .then(function (d) { когдаПоявятся(function () { держать(d); }); })
    .catch(function () { /* данных нет — числа остаются пустыми */ });
})();
